    #[test]
    fn concurrent_first_requests_create_one_safe_cache_file() {
        let data_dir = test_data_dir("concurrent-first");
        let source = data_dir.join("images/source.png");
        write_png(
            &source,
            RgbaImage::from_pixel(960, 480, Rgba([20, 40, 60, 255])),
        );
        let expected_path = source_path(&data_dir, "source.png");
        let results = std::thread::scope(|scope| {
            let mut tasks = Vec::new();
            for _ in 0..8 {
                tasks.push(scope.spawn(|| {
                    read_thumbnail_from_data_dir(
                        &data_dir,
                        "source.png",
                        &expected_path,
                        ThumbnailCacheConfig::default(),
                    )
                }));
            }
            tasks
                .into_iter()
                .map(|task| task.join().unwrap().unwrap())
                .collect::<Vec<_>>()
        });
        assert!(results.windows(2).all(|pair| pair[0] == pair[1]));
        assert_eq!(owned_cache_files(&data_dir).len(), 1);
        remove_test_data_dir(data_dir);
    }

    #[test]
    fn corrupt_or_oversized_cache_is_removed_and_rebuilt() {
        let data_dir = test_data_dir("corrupt-cache");
        let source = data_dir.join("images/source.png");
        write_png(
            &source,
            RgbaImage::from_pixel(640, 320, Rgba([220, 10, 10, 255])),
        );
        let original_thumbnail = thumbnail(&data_dir, "source.png");
        let cache_path = owned_cache_files(&data_dir).pop().unwrap();
        let truncated = &original_thumbnail[..original_thumbnail.len() / 2];
        let dimensions = ImageReader::new(Cursor::new(truncated))
            .with_guessed_format()
            .unwrap()
            .into_dimensions()
            .unwrap();
        assert_eq!(dimensions, (320, 160), "fixture retains a valid PNG IHDR");
        fs::write(&cache_path, truncated).unwrap();
        assert_eq!(thumbnail(&data_dir, "source.png"), original_thumbnail);

        fs::write(
            &cache_path,
            vec![0; (MAX_CACHED_THUMBNAIL_BYTES + 1) as usize],
        )
        .unwrap();
        assert_eq!(thumbnail(&data_dir, "source.png"), original_thumbnail);
        remove_test_data_dir(data_dir);
    }

